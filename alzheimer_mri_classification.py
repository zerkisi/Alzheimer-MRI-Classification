"""### 4.1 Statistical significance – McNemar's test
McNemar's test checks whether two classifiers make errors on *different* test images more often than chance
(H₀: both models have the same error rate). We use the exact binomial version when the number of discordant pairs is small.
"""

def mcnemar(y, a, b):
    ca, cb = a == y, b == y
    n01 = int(np.sum(ca & ~cb)); n10 = int(np.sum(~ca & cb))  # A right / B wrong, A wrong / B right
    if n01 + n10 == 0: return n01, n10, 1.0
    if n01 + n10 < 25:
        p = binomtest(min(n01, n10), n01 + n10, 0.5).pvalue
    else:
        stat = (abs(n01 - n10) - 1) ** 2 / (n01 + n10); p = 1 - chi2.cdf(stat, 1)
    return n01, n10, p

pairs = [("CNN", "ANN"), ("EfficientNetB0", "ANN"), ("EfficientNetB0", "CNN")]
mc = pd.DataFrame([dict(zip(["A", "B", "A right / B wrong", "A wrong / B right", "p_value"],
                            (a, b, *mcnemar(y_test, preds[a], preds[b])))) for a, b in pairs])
mc["significant (p<0.05)"] = mc.p_value < 0.05
