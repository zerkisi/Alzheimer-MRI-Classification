        ax = axes[i, j]
        ax.plot(h[m], label="train", color="#3b6ea5"); ax.plot(h["val_" + m], label="validation", color="#e39b3c")
        if n == "EfficientNetB0":
            ax.axvline(phase1_epochs - 0.5, ls="--", c="gray", lw=1); ax.text(phase1_epochs, ax.get_ylim()[1], " fine-tune", va="top", fontsize=8, color="gray")
        ax.set_title(f"{n} – {lab}"); ax.set_xlabel("epoch"); ax.spines[["top", "right"]].set_visible(False)
        if i == 0 and j == 0: ax.legend(frameon=False)
