"""## 5. Qualitative analysis
### 5.1 Grad-CAM – where does the CNN look?
Grad-CAM highlights the image regions that most increase the predicted class score. For a trustworthy model we hope to
see attention on brain tissue (ventricles, hippocampal / cortical regions) rather than on the background or skull.
"""

def grad_cam(model, img, layer_name="last_conv"):
    conv_layer = model.get_layer(layer_name)
    # build a graph that skips the augmentation layer (inference mode)
    grad_model = keras.Model(model.inputs, [conv_layer.output, model.output])
    with tf.GradientTape() as tape:
        conv_out, pred = grad_model(img[None], training=False)
        cls = int(tf.argmax(pred[0])); score = pred[:, cls]
    grads = tape.gradient(score, conv_out)
    w = tf.reduce_mean(grads, axis=(0, 1, 2))
    cam = tf.nn.relu(tf.reduce_sum(conv_out[0] * w, axis=-1)).numpy()
    cam = cam / (cam.max() + 1e-8)
    return tf.image.resize(cam[..., None], (IMG, IMG)).numpy()[..., 0], cls

