b2 = ax.bar(x + w/2, counts.test, w, label="Test", color="#e39b3c")
ax.bar_label(b1, fontsize=8); ax.bar_label(b2, fontsize=8)
ax.set_xticks(x, CLASS_NAMES); ax.set_ylabel("Number of images")
ax.set_title("Class distribution (strong imbalance)")
ax.spines[["top", "right"]].set_visible(False); ax.legend(frameon=False)
plt.savefig(f"{OUT}/fig_class_distribution.png"); plt.show()

fig, axes = plt.subplots(4, 5, figsize=(10, 8.4))
for c in range(4):
    idx = np.random.choice(np.where(y_trainval == c)[0], 5, replace=len(np.where(y_trainval == c)[0]) < 5)
    for j, i in enumerate(idx):
        axes[c, j].imshow(X_trainval[i], cmap="gray"); axes[c, j].axis("off")
    axes[c, 0].set_title(CLASS_NAMES[c], loc="left", fontsize=11, fontweight="bold")
plt.suptitle("Sample MRI slices per class", y=1.0)
plt.tight_layout(); plt.savefig(f"{OUT}/fig_samples.png"); plt.show()

print("Pixel mean/std:", X_trainval.mean().round(2), X_trainval.std().round(2))

"""### 2.2 Train / validation split and class weights
The provided test set is kept untouched until final evaluation. 15% of the training data is held out (stratified)
for validation / early stopping. Because *Moderate* has very few images, we use **class weights** in the loss.
"""

X_train, X_val, y_train, y_val = train_test_split(
    X_trainval, y_trainval, test_size=0.15, stratify=y_trainval, random_state=SEED)

def prep(X):  # (N,128,128) uint8 -> (N,128,128,1) float32 in [0,1]
    return (X.astype("float32") / 255.0)[..., None]

Xtr, Xva, Xte = prep(X_train), prep(X_val), prep(X_test)
cw = compute_class_weight("balanced", classes=np.arange(4), y=y_train)
CLASS_WEIGHT = dict(enumerate(cw))
print("train", Xtr.shape, "val", Xva.shape, "test", Xte.shape)
print("class weights:", {CLASS_NAMES[k]: round(v, 2) for k, v in CLASS_WEIGHT.items()})

"""## 3. Models"""

EPOCHS = 3 if SMOKE_TEST else None
BATCH = 32
histories, models, times = {}, {}, {}

def callbacks(patience=8):
    return [keras.callbacks.EarlyStopping(monitor="val_loss", patience=patience, restore_best_weights=True),
            keras.callbacks.ReduceLROnPlateau(monitor="val_loss", factor=0.5, patience=3, min_lr=1e-6)]

def fit(name, model, epochs, lr, patience=8, Xt=None, Xv=None):
    Xt = Xtr if Xt is None else Xt; Xv = Xva if Xv is None else Xv
    model.compile(optimizer=keras.optimizers.Adam(lr), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    t0 = time.time()
    h = model.fit(Xt, y_train, validation_data=(Xv, y_val), epochs=EPOCHS or epochs, batch_size=BATCH,
                  class_weight=CLASS_WEIGHT, callbacks=callbacks(patience), verbose=2)
    times[name] = times.get(name, 0) + time.time() - t0
    if name in histories:  # append second training phase
        for k in h.history: histories[name][k] += h.history[k]
    else:
        histories[name] = {k: list(v) for k, v in h.history.items()}
    models[name] = model
    return model

augment = keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.05),
    layers.RandomZoom(0.1),
    layers.RandomTranslation(0.05, 0.05),
], name="augmentation")

"""### 3.1 Model A – ANN (multilayer perceptron) baseline
Flattened 128×128 pixels → Dense(512) → Dense(256) → softmax. No notion of spatial structure;
this shows how much a CNN's inductive bias helps.
"""

ann = keras.Sequential([
    layers.Input((IMG, IMG, 1)),
    layers.Flatten(),
    layers.Dense(512, activation="relu"), layers.BatchNormalization(), layers.Dropout(0.4),
    layers.Dense(256, activation="relu"), layers.BatchNormalization(), layers.Dropout(0.4),
    layers.Dense(NUM_CLASSES, activation="softmax")], name="ANN")
ann.summary()
fit("ANN", ann, epochs=60, lr=1e-3, patience=10)

"""### 3.2 Model B – CNN from scratch
Four convolutional blocks (Conv–BN–ReLU ×2 + MaxPool, 32→256 filters), global average pooling,
dropout and a softmax head. Data augmentation (small rotations, shifts, zoom, horizontal flip) is applied on the fly.
"""

def conv_block(x, f, name=None):
    x = layers.Conv2D(f, 3, padding="same", use_bias=False)(x); x = layers.BatchNormalization()(x); x = layers.ReLU()(x)
    x = layers.Conv2D(f, 3, padding="same", use_bias=False, name=name)(x); x = layers.BatchNormalization()(x); x = layers.ReLU()(x)
    return layers.MaxPooling2D()(x)

inp = layers.Input((IMG, IMG, 1))
x = augment(inp)
for f in (32, 64, 128):
    x = conv_block(x, f)
x = conv_block(x, 256, name="last_conv")
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dropout(0.4)(x)
x = layers.Dense(128, activation="relu")(x)
x = layers.Dropout(0.3)(x)
out = layers.Dense(NUM_CLASSES, activation="softmax")(x)
cnn = keras.Model(inp, out, name="CNN")
cnn.summary()
fit("CNN", cnn, epochs=60, lr=1e-3, patience=10)

"""### 3.3 Model C – Transfer learning (EfficientNetB0, ImageNet weights)
The grayscale slice is repeated to 3 channels and fed to EfficientNetB0 (Keras' EfficientNet expects pixel values in
[0, 255] and normalizes internally).
* **Phase 1:** backbone frozen, only the new classification head is trained (lr = 1e-3).
* **Phase 2:** the top ~40% of the backbone is unfrozen and fine-tuned with a small learning rate (lr = 1e-5);
  BatchNorm layers stay frozen to keep pre-trained statistics.
"""

base = keras.applications.EfficientNetB0(include_top=False, weights=None if SMOKE_TEST else "imagenet",
                                         input_shape=(IMG, IMG, 3))
base.trainable = False

inp = layers.Input((IMG, IMG, 1))
x = augment(inp)
x = layers.Concatenate()([x, x, x])
x = layers.Rescaling(255.0)(x)
x = base(x, training=False)
x = layers.GlobalAveragePooling2D()(x)
x = layers.Dropout(0.4)(x)
out = layers.Dense(NUM_CLASSES, activation="softmax")(x)
tl = keras.Model(inp, out, name="EfficientNetB0_TL")

print("Phase 1: frozen backbone")
fit("EfficientNetB0", tl, epochs=15, lr=1e-3, patience=5)
phase1_epochs = len(histories["EfficientNetB0"]["loss"])

print("Phase 2: fine-tuning top layers")
base.trainable = True
n_freeze = int(len(base.layers) * 0.6)
for l in base.layers[:n_freeze]:
    l.trainable = False
for l in base.layers:
    if isinstance(l, layers.BatchNormalization):
        l.trainable = False
fit("EfficientNetB0", tl, epochs=40, lr=1e-5, patience=8)

"""### 3.4 Training curves"""

names = list(histories)
fig, axes = plt.subplots(2, len(names), figsize=(4.3 * len(names), 6.5), squeeze=False)
for j, n in enumerate(names):
    h = histories[n]
