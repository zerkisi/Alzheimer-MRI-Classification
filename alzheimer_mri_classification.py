"""## 2. Data

**Source:** `Falah/Alzheimer_MRI` on Hugging Face (Apache-2.0). It is a re-packaging of the widely used Kaggle
*Alzheimer MRI Preprocessed Dataset* (originally derived from ADNI): 6,400 axial grayscale MRI slices, 128×128 px,
pre-split into 5,120 train / 1,280 test images.

Label ids: `0 = Mild_Demented`, `1 = Moderate_Demented`, `2 = Non_Demented`, `3 = Very_Mild_Demented`.
We reorder them by disease severity for readability.
"""

ORIG_NAMES = ["Mild_Demented", "Moderate_Demented", "Non_Demented", "Very_Mild_Demented"]
# reorder by severity: Non -> Very mild -> Mild -> Moderate
CLASS_NAMES = ["Non Demented", "Very Mild", "Mild", "Moderate"]
REMAP = {2: 0, 3: 1, 0: 2, 1: 3}
NUM_CLASSES = 4
IMG = 128

def to_arrays(split):
    X = np.stack([np.array(im.convert("L").resize((IMG, IMG))) for im in split["image"]]).astype(np.uint8)
    y = np.array([REMAP[int(l)] for l in split["label"]], dtype=np.int64)
    return X, y

if not SMOKE_TEST:
    from datasets import load_dataset
    ds = load_dataset("Falah/Alzheimer_MRI")
    X_trainval, y_trainval = to_arrays(ds["train"])
    X_test, y_test = to_arrays(ds["test"])
else:  # synthetic stand-in with the same shapes / imbalance, for code testing only
    rng = np.random.default_rng(0)
    def fake(n):
        y = rng.choice(4, size=n, p=[.50, .35, .14, .01])
        X = (rng.random((n, IMG, IMG)) * 80 + y[:, None, None] * 40).astype(np.uint8)
        return X, y
    X_trainval, y_trainval = fake(640); X_test, y_test = fake(160)

print("train+val:", X_trainval.shape, " test:", X_test.shape)

"""### 2.1 Exploratory analysis: class distribution and sample images"""

counts = pd.DataFrame({
    "class": CLASS_NAMES,
    "train": np.bincount(y_trainval, minlength=4),
    "test": np.bincount(y_test, minlength=4)})
counts["total"] = counts.train + counts.test
counts["share_%"] = (100 * counts.total / counts.total.sum()).round(1)
display(counts)
counts.to_csv(f"{OUT}/class_distribution.csv", index=False)

